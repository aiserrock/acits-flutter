/// Вид документа, который открывает просмотрщик PDF.
///
/// Сериализуемое описание источника байтов: попадает в URL роута (`kind=<name>`),
/// а приложение по нему собирает загрузчик через DI. Так адрес `/doc-viewer`
/// остаётся валидным после перезагрузки страницы и навигации «назад/вперёд».
enum DocKind {
  /// PDF-карточка животного; `id` — идентификатор животного.
  animalCard;

  /// Вид по имени из URL, либо `null`, если имя неизвестно.
  static DocKind? fromName(String? name) => values.asNameMap()[name];
}
