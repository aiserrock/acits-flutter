/// Права пользователя в текущем приюте для действий над карточкой животного.
/// Мостится корнем к `AuthService.shelterRole` — модуль не знает про роли/авторизацию.
abstract interface class AnimalPermissions {
  /// Может ли пользователь редактировать животных (показывать action «Изменить»).
  bool get canEdit;

  /// Может ли пользователь удалять животных (показывать action «Удалить»).
  bool get canDelete;
}
