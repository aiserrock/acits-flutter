import 'dart:io';

/// Порт загрузки файла вложения комментария на устройство (только натив).
///
/// Экран списка комментариев на нативе скачивает файл во временный каталог и
/// открывает его системным вьювером. Модуль не знает про app `FileService` —
/// корень мостит этот порт к нему. На web порт не используется (файл
/// открывается по URL в браузере).
abstract interface class CommentFileOpener {
  /// Скачать и сохранить файл [url] под именем [title]; вернуть локальный файл.
  Future<File> loadFile(String url, String title);
}
